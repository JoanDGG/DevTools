using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace PixelPlay.Foundation.Networking
{
    /// <summary>Builds multipart/form-data requests containing text fields and binary files.</summary>
    /// <remarks>The request body is assembled in memory; use this for small and medium uploads.</remarks>
    public sealed class MultipartFormDataBuilder
    {
        private const string DefaultFileContentType = "application/octet-stream";
        private static readonly Encoding Utf8 = new UTF8Encoding(false);

        private readonly List<Part> _parts = new List<Part>();

        /// <summary>Adds a UTF-8 text field.</summary>
        public MultipartFormDataBuilder AddField(string name, string value)
        {
            ValidateHeaderValue(name, nameof(name));
            if (value == null)
                throw new ArgumentNullException(nameof(value));

            _parts.Add(new Part(name, null, null, Utf8.GetBytes(value)));
            return this;
        }

        /// <summary>Adds a binary file field.</summary>
        public MultipartFormDataBuilder AddFile(
            string fieldName,
            string fileName,
            string contentType,
            byte[] fileData)
        {
            ValidateHeaderValue(fieldName, nameof(fieldName));
            ValidateHeaderValue(fileName, nameof(fileName));
            ValidateHeaderValue(contentType, nameof(contentType));
            if (fileData == null)
                throw new ArgumentNullException(nameof(fileData));

            string safeFileName = GetFileName(fileName);
            if (safeFileName.Length == 0)
                throw new ArgumentException("File name must include a name after its path.", nameof(fileName));

            _parts.Add(new Part(fieldName, safeFileName, contentType, (byte[])fileData.Clone()));
            return this;
        }

        /// <summary>Builds a request with the generated boundary and multipart content type.</summary>
        public HttpRequestData BuildRequest(
            string url,
            string method = "POST",
            IDictionary<string, string> headers = null,
            int timeoutSeconds = 30)
        {
            if (_parts.Count == 0)
                throw new InvalidOperationException("Add at least one field or file before building the request.");

            string boundary = "----PixelPlayFoundation_" + Guid.NewGuid().ToString("N");
            byte[] body = BuildBody(boundary);
            var requestHeaders = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);

            if (headers != null)
            {
                foreach (KeyValuePair<string, string> header in headers)
                {
                    if (string.Equals(header.Key, "Content-Type", StringComparison.OrdinalIgnoreCase))
                    {
                        throw new ArgumentException(
                            "Content-Type is generated by the multipart builder and must not be overridden.",
                            nameof(headers));
                    }

                    requestHeaders.Add(header.Key, header.Value);
                }
            }

            requestHeaders.Add("Content-Type", "multipart/form-data; boundary=" + boundary);
            return new HttpRequestData(url, method, body, requestHeaders, timeoutSeconds);
        }

        private byte[] BuildBody(string boundary)
        {
            using (var stream = new MemoryStream())
            {
                for (int i = 0; i < _parts.Count; i++)
                {
                    Part part = _parts[i];
                    WriteUtf8(stream, "--" + boundary + "\r\n");
                    WriteUtf8(stream, "Content-Disposition: form-data; name=\"" + EscapeQuotedString(part.Name) + "\"");

                    if (part.FileName != null)
                    {
                        string encodedName = Uri.EscapeDataString(part.FileName);
                        WriteUtf8(stream, "; filename=\"" + EscapeQuotedString(encodedName) + "\"");
                    }

                    WriteUtf8(stream, "\r\n");
                    if (part.ContentType != null)
                        WriteUtf8(stream, "Content-Type: " + part.ContentType + "\r\n");
                    else
                        WriteUtf8(stream, "Content-Type: text/plain; charset=utf-8\r\n");

                    WriteUtf8(stream, "\r\n");
                    stream.Write(part.Data, 0, part.Data.Length);
                    WriteUtf8(stream, "\r\n");
                }

                WriteUtf8(stream, "--" + boundary + "--\r\n");
                return stream.ToArray();
            }
        }

        private static string GetFileName(string pathOrFileName)
        {
            int separatorIndex = Math.Max(pathOrFileName.LastIndexOf('/'), pathOrFileName.LastIndexOf('\\'));
            return separatorIndex >= 0 ? pathOrFileName.Substring(separatorIndex + 1) : pathOrFileName;
        }

        private static string EscapeQuotedString(string value) =>
            value.Replace("\\", "\\\\").Replace("\"", "\\\"");

        private static void ValidateHeaderValue(string value, string parameterName)
        {
            if (string.IsNullOrWhiteSpace(value))
                throw new ArgumentException("Value must not be null or whitespace.", parameterName);

            foreach (char character in value)
            {
                if (char.IsControl(character))
                    throw new ArgumentException("Value must not contain control characters.", parameterName);
            }
        }

        private static void WriteUtf8(Stream stream, string value)
        {
            byte[] bytes = Utf8.GetBytes(value);
            stream.Write(bytes, 0, bytes.Length);
        }

        private sealed class Part
        {
            public Part(string name, string fileName, string contentType, byte[] data)
            {
                Name = name;
                FileName = fileName;
                ContentType = contentType;
                Data = data;
            }

            public string Name { get; }
            public string FileName { get; }
            public string ContentType { get; }
            public byte[] Data { get; }
        }
    }
}
